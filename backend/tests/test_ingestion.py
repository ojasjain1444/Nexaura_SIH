def test_upload_endpoint_registers_and_returns_document(client, isolated_storage):
    content = _read_fixture("test_text.pdf")
    response = client.post(
        "/api/documents/upload", files={"file": ("test_text.pdf", content, "application/pdf")}
    )
    assert response.status_code == 201
