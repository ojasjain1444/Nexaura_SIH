"""
Document ingestion pipeline tests.

All PDFs used here are the SYNTHETIC TEST FIXTURES generated by
tests/fixtures/generate_test_pdfs.py — never real BIS documents. Each
fixture's own text explicitly says "SYNTHETIC TEST DOCUMENT -- NOT AN
OFFICIAL BIS STANDARD". These tests verify pipeline mechanics (does
extraction/OCR/status-tracking work), not real BIS content accuracy.
"""

from pathlib import Path

import pytest

from app.ingestion.validation import DocumentValidationError, compute_file_hash, validate_upload
from app.services.document_service import DocumentService, DuplicateDocumentError

FIXTURES_DIR = Path(__file__).parent / "fixtures"


def _read_fixture(name: str) -> bytes:
    return (FIXTURES_DIR / name).read_bytes()


# --- Validation ---


def test_valid_pdf_passes_validation():
    content = _read_fixture("test_text.pdf")
    validate_upload(content, "application/pdf", "test_text.pdf")  # should not raise


def test_invalid_file_rejected():
    content = _read_fixture("test_invalid.txt")
    with pytest.raises(DocumentValidationError, match="valid PDF"):
        validate_upload(content, "application/pdf", "test_invalid.txt")


def test_empty_content_rejected():
    with pytest.raises(DocumentValidationError, match="empty"):
        validate_upload(b"", "application/pdf", "empty.pdf")


def test_wrong_mime_type_rejected():
    content = _read_fixture("test_text.pdf")
    with pytest.raises(DocumentValidationError, match="Unsupported file type"):
        validate_upload(content, "image/png", "test_text.pdf")


def test_oversized_file_rejected():
    fake_large_content = b"%PDF-1.4\n" + b"0" * (51 * 1024 * 1024)
    with pytest.raises(DocumentValidationError, match="exceeds"):
        validate_upload(fake_large_content, "application/pdf", "big.pdf")


# --- End-to-end pipeline (service layer, isolated DB + storage) ---


def test_text_pdf_end_to_end(db_session, isolated_storage):
    service = DocumentService(db_session)
    content = _read_fixture("test_text.pdf")
    document = service.register_upload(content, "test_text.pdf", "application/pdf", source_type="test")
    assert document.status == "uploaded"

    result = service.process_document(document.id, content)
    assert result.status == "completed"
    assert result.page_count == 1
    assert result.extracted_standard_number == "IS 99999"

    pages = service.get_pages(document.id)
    assert len(pages) == 1
    assert pages[0].extraction_method == "native"
    assert "SYNTHETIC TEST DOCUMENT" in pages[0].text


