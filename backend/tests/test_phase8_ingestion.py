def test_ingest_and_index_cli_reports_pipeline_failure_without_indexing(tmp_path, monkeypatch, isolated_storage):
    """A corrupt/invalid PDF must fail at the ingestion stage and never
    reach indexing — the CLI must report which stage failed."""
    import app.ingestion.ingest_and_index as cli_module
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from tests.conftest import create_all_tables

    db_path = tmp_path / "cli_fail_test.db"
    engine = create_engine(f"sqlite:///{db_path}", connect_args={"check_same_thread": False})
    create_all_tables(engine)
    TestSessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    monkeypatch.setattr(cli_module, "SessionLocal", TestSessionLocal)

    # A validation failure (invalid file) is caught before any document is
    # even registered — a distinct, earlier failure point than a pipeline
    # failure, and it must also report cleanly rather than crashing.
    invalid_copy = tmp_path / "test_invalid.txt"
    invalid_copy.write_bytes(_read_fixture("test_invalid.txt"))
    # validate_upload rejects based on mime_type/header; the CLI always
    # passes mime_type="application/pdf", so this exercises the missing
    # %PDF- header check specifically.
    exit_code = run_ingest_and_index(str(invalid_copy))
    assert exit_code == 1

    session = TestSessionLocal()
    try:
        from app.models.standard_document import StandardDocument

        assert session.query(StandardDocument).count() == 0
    finally:
        session.close()
    engine.dispose()
