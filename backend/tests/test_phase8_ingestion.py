def test_ingest_and_index_cli_runs_full_pipeline_and_indexes(tmp_path, monkeypatch, isolated_storage):
    """Runs the real CLI entrypoint end-to-end against an isolated SQLite
    DB (never the developer's real bis_sahayak.db), verifying it performs
    registration + ingestion + indexing as one operation and reports
    success only once chunks are actually created and embedded."""
    import app.ingestion.ingest_and_index as cli_module
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker

    from tests.conftest import create_all_tables

    db_path = tmp_path / "cli_test.db"
    engine = create_engine(f"sqlite:///{db_path}", connect_args={"check_same_thread": False})
    create_all_tables(engine)
    TestSessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    monkeypatch.setattr(cli_module, "SessionLocal", TestSessionLocal)

    fixture_copy = tmp_path / "test_text.pdf"
    fixture_copy.write_bytes(_read_fixture("test_text.pdf"))

    exit_code = run_ingest_and_index(str(fixture_copy))
    assert exit_code == 0

    session = TestSessionLocal()
    try:
        from app.models.document_chunk import DocumentChunk
        from app.models.standard_document import StandardDocument

        documents = session.query(StandardDocument).all()
        assert len(documents) == 1
        assert documents[0].status == "completed"

        chunks = session.query(DocumentChunk).filter_by(document_id=documents[0].id).all()
        assert len(chunks) > 0
        assert all(c.embedding_json is not None for c in chunks)
    finally:
        session.close()
    engine.dispose()


