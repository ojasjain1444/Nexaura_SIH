# --- Table-structure preservation in extraction ---


def test_native_page_with_table_produces_delimited_table_block():
    content = _read_fixture("test_table.pdf")
    pages = extract_pdf_pages(content, TesseractOCRProvider())

    assert len(pages) == 1
    text = pages[0].text
    assert "[TABLE]" in text
    assert "[/TABLE]" in text
    # Cell values from the fixture's table must survive, pipe-delimited.
    assert "Size | Tolerance | Grade" in text
    assert "10mm | +/-0.5 | A" in text


def test_page_without_table_is_unaffected():
    content = _read_fixture("test_text.pdf")
    pages = extract_pdf_pages(content, TesseractOCRProvider())

    assert "[TABLE]" not in pages[0].text
    assert "1 SCOPE" in pages[0].text


